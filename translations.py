def t(key: str, lang: str = "en", **kwargs) -> str:
    """
    Get translation for a key in the given language.
    Falls back to English if key/lang not found.
    Supports format kwargs e.g. t("sos_sent", lang, n=3)
    """
    text = TRANSLATIONS.get(key, {}).get(lang) or TRANSLATIONS.get(key, {}).get("en", key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text
